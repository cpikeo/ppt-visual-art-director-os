"""Honest brief -> plan -> untouched skeleton -> release check probe.
The skeleton is generated by the skill; no human/agent fills its elements.
Writes review/autonomy-probe.json; temp files remain outside the repository.
"""
import json
import runpy
import subprocess
import sys
import tempfile
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
CASE_DATA = [
 ('education_4',dict(audience='学校理事会',decision='评估试点',tension='课程质量差异',slides=[
   dict(id=f's{i:02d}',title=t,content=c) for i,(t,c) in enumerate([
      ('缺课率仍高于目标','本季度缺课率11%；目标低于8%；来源：教务系统。'),
      ('两个班级不能拼成一个整体','甲班通过率35%；乙班通过率65%；班级分母不同。'),
      ('改进要先确定归因','教师访谈显示调整意愿；目前无因果实验。'),
      ('请评估下学期试点','分校名单与预算尚待批准。')],1)])),
 ('factory_6',dict(audience='制造企业运维负责人',decision='审批维保计划',tension='停机影响',slides=[
   dict(id=f's{i:02d}',title=t,content=c) for i,(t,c) in enumerate([
      ('关键设备停机时间仍偏长','年度台账：停机42小时；来源：设备日志。'),
      ('故障发生在两个站点','A厂19次，B厂11次；两组不共享设备分母。'),
      ('维修周期由19天降至11天','同型号设备按相同口径比较。'),
      ('职责并列不是流程','甲组负责巡检；乙组负责培训。'),
      ('传感器报警不能当作原因','相关性未经过现场验证。'),
      ('请审批分批维保','预算和停机窗口待确认。')],1)])),
 ('health_8',dict(audience='医院伦理委员会',decision='决定是否扩展研究',tension='有效性与安全性混淆',slides=[
   dict(id=f's{i:02d}',title=t,content=c) for i,(t,c) in enumerate([
      ('研究结论仍受样本限制','当前属于内部验证，不可外推。'),
      ('响应率与不良反应不是一个整体','响应率60%；不良反应发生率40%；同一患者可能同时满足。'),
      ('入组不等于完成随访','36人入组，28人完成全部随访。'),
      ('不同站点不能共享分母','站点甲15人，站点乙21人。'),
      ('效果尚不足以推断因果','尚未设置随机对照。'),
      ('病例记录只作可追溯凭证','不得用合成图伪装真实影像。'),
      ('缺失值需要明确披露','有8人尚未完成随访。'),
      ('请决定是否扩展研究','先复核安全性与样本范围。')],1)]))]
with tempfile.TemporaryDirectory(prefix='vao-autonomy-') as td:
    results=[]
    for case,brief in CASE_DATA:
        d=Path(td)/case; d.mkdir()
        b=d/'brief.json';b.write_text(json.dumps(brief,ensure_ascii=False),encoding='utf-8')
        plan=d/'plan.json';skel=d/'build.py';out=d/'out.pptx'
        cmd=[sys.executable,str(ROOT/'scripts/vao.py')]
        a=subprocess.run(cmd+['plan',str(b),'--out',str(plan),'--skeleton',str(skel),'--json'],
                         capture_output=True,encoding='utf-8',cwd=ROOT)
        if a.returncode: raise RuntimeError(a.stderr)
        spec=runpy.run_path(str(skel))['SPEC']
        unfilled=sum(len(p['elements']) for p in spec['slides'])
        v=subprocess.run(cmd+['check',str(skel),str(out),'--mode','release',
                              '--speed','strict','--json'],capture_output=True,encoding='utf-8',cwd=ROOT)
        try: reply=json.loads(v.stdout)
        except json.JSONDecodeError: reply={'stdout_tail':v.stdout[-500:],'stderr_tail':v.stderr[-500:]}
        results.append({'case':case,'pages':len(spec['slides']),'generated_elements':unfilled,
                        'plan_status':'PASS','check_exit':v.returncode,'release_status':reply.get('status'),
                        'codes':reply.get('failure_codes'),
                        'true_auto_build_verified':False})
    target=ROOT/'review/autonomy-probe.json'
    target.write_text(json.dumps(results,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    print(json.dumps(results,ensure_ascii=False,indent=2))
